X = cooling_df[["delta_T", "GHI"]].values
y = cooling_df["cooling_kWh"].values

# 4.Regression Model Training
model = LinearRegression().fit(X, y)

# 5. Generate a Model Sheet( surface)
x_surf, y_surf = np.meshgrid(
    np.linspace(X[:, 0].min(), X[:, 0].max(), 20),
    np.linspace(X[:, 1].min(), X[:, 1].max(), 20)
)
z_surf = model.predict(np.c_[x_surf.ravel(), y_surf.ravel()]).reshape(x_surf.shape)

