    fig = plt.figure(figsize=(8, 6))
    ax = fig.add_subplot(111, projection='3d')

    # Real Point
    ax.scatter(X[:, 0], X[:, 1], y, c='red', alpha=0.5, label="Cooling Data")

    # Sheet model
    ax.plot_surface(x_surf, y_surf, z_surf, alpha=0.3, color='blue')

