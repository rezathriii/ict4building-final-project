import pandas as pd
from sklearn.linear_model import LinearRegression
from sklearn.metrics import r2_score

# Read Dta
df_old = pd.read_csv("energy_signature_old_with_ghi.csv")
df_opt = pd.read_csv("energy_signature_opt_with_ghi.csv")

df_old["time"] = pd.to_datetime(df_old["time"])
df_opt["time"] = pd.to_datetime(df_opt["time"])

# Only Warm months and Active Cooling
df_old_cooling = df_old[(df_old["time"].dt.month.isin([6, 7, 8, 9])) & (df_old["cooling_kWh"] > 0)].copy()
df_opt_cooling = df_opt[(df_opt["time"].dt.month.isin([6, 7, 8, 9])) & (df_opt["cooling_kWh"] > 0)].copy()

# Applying a Conditional Filter to Cooling
mask_old = (df_old_cooling["delta_T"] > -2) & (df_old_cooling["cooling_kWh"] > 7)
mask_opt = (df_opt_cooling["delta_T"] > -2) & (df_opt_cooling["cooling_kWh"] > 7)

print("Remove Cold Weather Records:")
print(" - Befor Optimization  :", mask_old.sum())
print(" - After Optimazation :", mask_opt.sum())

df_old_cooling = df_old_cooling[~mask_old]
df_opt_cooling = df_opt_cooling[~mask_opt]

# Add a clock column for cold weather
df_old_cooling["hour"] = df_old_cooling["time"].dt.hour
df_opt_cooling["hour"] = df_opt_cooling["time"].dt.hour

# Calculation Function R²
def compute_r2_grouped(df, time_col, target_col, group_freq, feature_cols):
    df["group_time"] = df[time_col].dt.to_period(group_freq).apply(lambda r: r.start_time)
    grouped = df.groupby("group_time").agg({col: "mean" for col in feature_cols + [target_col]}).dropna()
    X = grouped[feature_cols]
    y = grouped[target_col]
    model = LinearRegression().fit(X, y)
    return r2_score(y, model.predict(X))

# Cooling: Multivariate Model
cooling_results = {}
for freq, label in zip(["H", "D", "W"], ["Hourly", "Daily", "Weekly"]):
    r2_old = compute_r2_grouped(df_old_cooling.copy(), "time", "cooling_kWh", freq, ["delta_T", "GHI", "hour"])
    r2_opt = compute_r2_grouped(df_opt_cooling.copy(), "time", "cooling_kWh", freq, ["delta_T", "GHI", "hour"])
    cooling_results[label] = (r2_old, r2_opt)

# Heating: Univariate Model
heating_results = {}
for freq, label in zip(["H", "D", "W"], ["Hourly", "Daily", "Weekly"]):
    r2_old = compute_r2_grouped(df_old.copy(), "time", "heating_kWh", freq, ["delta_T"])
    r2_opt = compute_r2_grouped(df_opt.copy(), "time", "heating_kWh", freq, ["delta_T"])
    heating_results[label] = (r2_old, r2_opt)

# Final Display of The Table
print("\n📊 R² Comparison (after removing outlier cooling data):")
print(f"{'':<10} | {'Hourly':^20} | {'Daily':^20} | {'Weekly':^20}")
print("-" * 75)
for label, results in [("Heating", heating_results), ("Cooling", cooling_results)]:
    h = results["Hourly"]
    d = results["Daily"]
    w = results["Weekly"]
    print(f"{label:<10} | {h[0]:.3f} → {h[1]:.3f}    | {d[0]:.3f} → {d[1]:.3f}    | {w[0]:.3f} → {w[1]:.3f}")



